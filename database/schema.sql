DROP TABLE IF EXISTS DETALLE_VENTAS;
DROP TABLE IF EXISTS MOVIMIENTOS_INVENTARIO;
DROP TABLE IF EXISTS VENTAS;
DROP TABLE IF EXISTS PRODUCTOS;
DROP TABLE IF EXISTS CATEGORIAS;
DROP TABLE IF EXISTS CLIENTES;
DROP TABLE IF EXISTS AVATARES;
DROP TABLE IF EXISTS USUARIOS_ROLES;
DROP TABLE IF EXISTS USUARIOS;
DROP TABLE IF EXISTS PERFIL_USUARIOS;
DROP TABLE IF EXISTS ROLES;

CREATE TABLE IF NOT EXISTS ROLES(
    ID_ROL BIGSERIAL PRIMARY KEY,
    NOMBRE VARCHAR(50) UNIQUE NOT NULL,
    DESCRIPCION VARCHAR(150) NOT NULL
    );

CREATE TABLE IF NOT EXISTS PERFIL_USUARIOS(
    ID_PERFIL BIGSERIAL PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO_PATERNO VARCHAR(50) NOT NULL,
    APELLIDO_MATERNO VARCHAR(50) NOT NULL,
    TELEFONO VARCHAR(10) NOT NULL,
    DIRECCION VARCHAR(150) NOT NULL,
    FECHA_NACIMIENTO DATE NOT NULL,
    CONSTRAINT CHK_PERFIL_TELEFONO CHECK (TELEFONO ~ '^[0-9]{10}$')
    );

CREATE TABLE IF NOT EXISTS USUARIOS(
    ID_USUARIO BIGSERIAL PRIMARY KEY,
    ID_PERFIL BIGINT UNIQUE NOT NULL REFERENCES PERFIL_USUARIOS(ID_PERFIL),
    NOMBRE_USUARIO VARCHAR(50) NOT NULL,
    PASSWORD_HASH VARCHAR(150) NOT NULL,
    CORREO VARCHAR(100) NOT NULL,
    ESTADO_USUARIO VARCHAR(50) NOT NULL
    CHECK (ESTADO_USUARIO IN ('ACTIVO','ELIMINADO','BLOQUEADO')),
    FECHA_REGISTRO TIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP NOT NULL
    );

CREATE UNIQUE INDEX UQ_USUARIOS_USERNAME_ACTIVO
    ON USUARIOS(LOWER(NOMBRE_USUARIO))
    WHERE ESTADO_USUARIO = 'ACTIVO';

CREATE UNIQUE INDEX UQ_USUARIOS_CORREO_ACTIVO
    ON USUARIOS(LOWER(CORREO))
    WHERE ESTADO_USUARIO = 'ACTIVO';

CREATE TABLE IF NOT EXISTS USUARIOS_ROLES(
    ID_USUARIO BIGINT NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    ID_ROL BIGINT NOT NULL REFERENCES ROLES(ID_ROL),
    PRIMARY KEY (ID_USUARIO, ID_ROL)
    );

CREATE INDEX IDX_USUARIOS_ROLES_ID_ROL
    ON USUARIOS_ROLES(ID_ROL);

CREATE TABLE IF NOT EXISTS AVATARES(
    ID_IMAGEN BIGSERIAL PRIMARY KEY,
    ID_PERFIL BIGINT UNIQUE NOT NULL REFERENCES PERFIL_USUARIOS(ID_PERFIL),
    NOMBRE VARCHAR(100) NOT NULL,
    CONTENIDO BYTEA NOT NULL
    );

CREATE TABLE IF NOT EXISTS CLIENTES(
    ID_CLIENTE BIGSERIAL PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO_PATERNO VARCHAR(50) NOT NULL,
    APELLIDO_MATERNO VARCHAR(50) NOT NULL,
    CORREO VARCHAR(100) NOT NULL,
    TELEFONO VARCHAR(10) NOT NULL,
    DIRECCION VARCHAR(150) NOT NULL,
    FECHA_REGISTRO TIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP NOT NULL,
    ESTADO_CLIENTE VARCHAR(50) NOT NULL
    CHECK (ESTADO_CLIENTE IN ('ACTIVO','ELIMINADO','INACTIVO')),
    CONSTRAINT CHK_CLIENTES_TELEFONO CHECK (TELEFONO ~ '^[0-9]{10}$')
    );

CREATE UNIQUE INDEX UQ_CLIENTES_CORREO_ACTIVO
    ON CLIENTES(LOWER(CORREO))
    WHERE ESTADO_CLIENTE = 'ACTIVO';

CREATE UNIQUE INDEX UQ_CLIENTES_TELEFONO_ACTIVO
    ON CLIENTES(TELEFONO)
    WHERE ESTADO_CLIENTE = 'ACTIVO';

CREATE TABLE IF NOT EXISTS CATEGORIAS(
    ID_CATEGORIA BIGSERIAL PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    DESCRIPCION VARCHAR(100) NOT NULL,
    ESTADO_CATEGORIA VARCHAR(50)  NOT NULL
    CHECK (ESTADO_CATEGORIA IN ('ACTIVO', 'ELIMINADO')),
    FECHA_REGISTRO TIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP NOT NULL
    );

CREATE UNIQUE INDEX UQ_CATEGORIAS_NOMBRE_ACTIVO
    ON CATEGORIAS(LOWER(NOMBRE))
    WHERE ESTADO_CATEGORIA = 'ACTIVO';


CREATE TABLE IF NOT EXISTS PRODUCTOS(
    ID_PRODUCTO BIGSERIAL PRIMARY KEY,
    ID_CATEGORIA BIGINT NOT NULL REFERENCES CATEGORIAS(ID_CATEGORIA),
    VERSION BIGINT NOT NULL DEFAULT 0,
    SKU_PRODUCTO VARCHAR(50) UNIQUE NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    DESCRIPCION VARCHAR(150) NOT NULL,
    PRECIO_COMPRA NUMERIC(12,2) NOT NULL CHECK(PRECIO_COMPRA > 0),
    PRECIO_VENTA NUMERIC(12,2) NOT NULL CHECK(PRECIO_VENTA > 0),
    STOCK INTEGER NOT NULL CHECK(STOCK >= 0),
    STOCK_MINIMO INTEGER NOT NULL CHECK ( STOCK_MINIMO >= 0),
    ESTADO_PRODUCTO VARCHAR(50) NOT NULL
    CHECK(ESTADO_PRODUCTO IN ('ACTIVO','ELIMINADO', 'INACTIVO')),
    FECHA_REGISTRO TIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP NOT NULL
    );

CREATE INDEX IDX_PRODUCTOS_NOMBRE
    ON PRODUCTOS(NOMBRE);

CREATE TABLE IF NOT EXISTS VENTAS(
    ID_VENTA BIGSERIAL PRIMARY KEY,
    ID_CLIENTE BIGINT NOT NULL REFERENCES CLIENTES(ID_CLIENTE),
    ID_USUARIO BIGINT NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    FOLIO VARCHAR(20) NOT NULL UNIQUE ,
    FECHA_VENTA TIMESTAMP NOT NULL,
    DESCUENTO DECIMAL(12,2) NOT NULL DEFAULT 0,
    SUBTOTAL DECIMAL(12,2) NOT NULL,
    IMPUESTOS DECIMAL (12,2) NOT NULL DEFAULT 0,
    TOTAL DECIMAL (12,2) NOT NULL DEFAULT 0,
    ESTADO_VENTA VARCHAR(50) NOT NULL
    CHECK (ESTADO_VENTA IN ('BORRADOR', 'CONFIRMADA', 'CANCELADA'))
    );

CREATE INDEX IDX_VENTAS_FECHA_VENTA
    ON VENTAS(FECHA_VENTA);

CREATE INDEX IDX_VENTAS_ESTADO_FECHA
    ON VENTAS(ESTADO_VENTA, FECHA_VENTA);

CREATE TABLE IF NOT EXISTS MOVIMIENTOS_INVENTARIO(
    ID_INVENTARIO BIGSERIAL PRIMARY KEY,
    ID_PRODUCTO BIGINT NOT NULL REFERENCES PRODUCTOS(ID_PRODUCTO),
    ID_USUARIO BIGINT NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    ID_VENTA BIGINT  REFERENCES VENTAS(ID_VENTA),
    TIPO_MOVIMIENTO VARCHAR(50) NOT NULL
    CHECK (TIPO_MOVIMIENTO IN ('ENTRADA', 'VENTA', 'CANCELACION_VENTA', 'AJUSTE_POSITIVO', 'AJUSTE_NEGATIVO')),
    CANTIDAD_PRODUCTO INTEGER NOT NULL CHECK (CANTIDAD_PRODUCTO > 0),
    STOCK_ANTERIOR INTEGER NOT NULL,
    STOCK_ACTUAL INTEGER NOT NULL CHECK (STOCK_ACTUAL >= 0),
    FECHA_REGISTRO TIMESTAMP NOT NULL,
    MOTIVO VARCHAR(100) NOT NULL
    );

CREATE INDEX IDX_MOVIMIENTOS_PRODUCTO_FECHA
    ON MOVIMIENTOS_INVENTARIO(ID_PRODUCTO, FECHA_REGISTRO);

CREATE TABLE IF NOT EXISTS DETALLE_VENTAS(
    ID_DETALLE_VENTA BIGSERIAL PRIMARY KEY,
    ID_VENTA BIGINT NOT NULL REFERENCES VENTAS(ID_VENTA),
    ID_PRODUCTO BIGINT NOT NULL REFERENCES PRODUCTOS(ID_PRODUCTO),
    CANTIDAD_PRODUCTO INTEGER NOT NULL CHECK (CANTIDAD_PRODUCTO > 0),
    PRECIO_UNITARIO DECIMAL(12,2) NOT NULL,
    DESCUENTO DECIMAL(12,2) NOT NULL DEFAULT 0,
    SUBTOTAL DECIMAL(12,2) NOT NULL
    );

CREATE INDEX IDX_DETALLE_VENTAS_ID_VENTA
    ON DETALLE_VENTAS(ID_VENTA);
